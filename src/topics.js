// 뒷말이 무엇을 묻는지 찾아 줍니다.
const categoryOf = (modifier) => CATEGORIES.find((item) => item.match.test(String(modifier ?? ''))) || DEFAULT_CATEGORY;

// 소제목 한 개를 통째로 만들어 줍니다. 같은 분류가 두 번 나와도 다른 문장이 나오도록 번갈아 씁니다.
const buildTopicSection = (keyword, modifier, index = 0) => {
  const category = categoryOf(modifier);
  let variant = index % 2;
  // 소제목 안에서 같은 말이 두 번 나오면 다른 표현을 씁니다.
  const repeated = (text) => String(text).split(modifier).length > 2;
  if (repeated(category.headings[variant](keyword, modifier))) {
    variant = (variant + 1) % 2;
  }
  return {
    categoryId: category.id,
    heading: category.headings[variant](keyword, modifier),
    paragraphs: category.paragraphs[variant](keyword, modifier),
    highlight: category.highlights[variant](keyword, modifier),
    imageQuery: category.images[index % category.images.length],
    imageCaption: `${keyword} ${modifier}`.slice(0, 28),
  };
};

